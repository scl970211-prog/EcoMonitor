def main():
    import sys
    import os
    
    # 读取原始文件
    with open('src/core/scanner/device_info.py', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 查找DEFAULT_OUI_DB的开始位置
    start_marker = 'DEFAULT_OUI_DB = {'
    end_marker = '}'
    
    start_idx = content.find(start_marker)
    if start_idx == -1:
        print("无法找到DEFAULT_OUI_DB")
        return
    
    # 找到匹配的结束括号
    brace_count = 0
    end_idx = start_idx
    for i, c in enumerate(content[start_idx:]):
        if c == '{':
            brace_count += 1
        elif c == '}':
            brace_count -= 1
            if brace_count == 0:
                end_idx = start_idx + i + 1
                break
    
    # 构建新的数据库内容
    lines = ['DEFAULT_OUI_DB = {']
    lines.append('    # 虚拟化平台')
    for key, value in sorted(EXTRA_OUI_ENTRIES.items()):
        lines.append(f'    "{key}": "{value}",')
    lines.append('}')
    
    new_db = '\n'.join(lines)
    
    # 替换
    new_content = content[:start_idx] + new_db + content[end_idx:]
    
    # 写回
    with open('src/core/scanner/device_info.py', 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    print(f"OUI数据库已更新，包含 {len(EXTRA_OUI_ENTRIES)} 个条目")

if __name__ == "__main__":
    main()
