class DeviceInfoResolver:
    """设备信息解析器 - 支持本地数据库和联网查询"""

    def __init__(self, enable_online_lookup: bool = True, online_timeout: float = 2.0):
        """
        初始化解析器
        
        Args:
            enable_online_lookup: 是否启用联网查询厂商信息
            online_timeout: 联网查询超时时间（秒）
        """
        self.oui_db = self._load_oui_db()
        self.enable_online_lookup = enable_online_lookup
        self.online_timeout = online_timeout
        # 联网查询结果缓存（避免重复查询）
        self._online_cache: Dict[str, str] = {}
        # 记录最近查询时间（用于限速）
        self._last_query_time = 0
        # 最小查询间隔（秒），免费 API 通常限制 1 请求/秒
        self._min_query_interval = 1.0

    def _load_oui_db(self) -> Dict[str, str]:
        """加载OUI数据库"""
        try:
            db_path = Path(__file__).parent.parent / "data" / "oui_database.json"
            if db_path.exists():
                with open(db_path, "r", encoding="utf-8") as f:
                    return json.load(f)
        except Exception:
            pass
        return DEFAULT_OUI_DB.copy()

    def _query_vendor_online(self, mac_address: str) -> str:
        """
        联网查询厂商信息
        
        使用 macvendors.com 免费 API（限速 1 请求/秒）
        
        Args:
            mac_address: 完整 MAC 地址
            
        Returns:
            str: 厂商名称，失败返回空字符串
        """
        if not self.enable_online_lookup:
            return ""
        
        # 标准化 MAC 地址
        mac_clean = mac_address.upper().replace(":", "").replace("-", "").replace(".", "")
        if len(mac_clean) != 12:
            return ""
        
        # 检查缓存
        mac_prefix = mac_clean[:6]
        if mac_prefix in self._online_cache:
            return self._online_cache[mac_prefix]
        
        # 限速检查
        import time
        current_time = time.time()
        time_since_last = current_time - self._last_query_time
        if time_since_last < self._min_query_interval:
            # 如果距离上次查询时间太短，跳过本次联网查询
            return ""
        
        try:
            import urllib.request
            import urllib.error
            
            url = f"https://api.macvendors.com/{mac_clean}"
            
            req = urllib.request.Request(
                url,
                headers={
                    "User-Agent": "EcoMonitor-Scanner/1.0",
                    "Accept": "text/plain"
                }
            )
            
            with urllib.request.urlopen(req, timeout=self.online_timeout) as response:
                self._last_query_time = time.time()
                if response.status == 200:
                    vendor = response.read().decode("utf-8").strip()
                    if vendor and vendor != "Not Found":
                        # 缓存结果
                        self._online_cache[mac_prefix] = vendor
                        return vendor
                        
        except urllib.error.HTTPError as e:
            # 429 Too Many Requests 或其他错误
            if e.code == 429:
                # 被限速，增加查询间隔
                self._min_query_interval = min(self._min_query_interval * 2, 5.0)
        except Exception:
            pass
        
        return ""

    def get_vendor(self, mac_address: str, try_online: bool = True) -> str:
        """
        根据MAC地址获取厂商信息

        Args:
            mac_address: MAC地址 (格式: XX:XX:XX:XX:XX:XX 或 XX-XX-XX-XX-XX-XX)
            try_online: 本地查询失败时是否尝试联网查询

        Returns:
            str: 厂商名称，未知返回空字符串
        """
        if not mac_address or mac_address in (
            "00:00:00:00:00:00",
            "FF:FF:FF:FF:FF:FF",
        ):
            return ""

        # 统一格式为 XX:XX:XX
        mac_prefix = mac_address.upper().replace("-", ":")[:8]

        # 首先查询本地数据库
        vendor = self.oui_db.get(mac_prefix, "")
        if vendor:
            return vendor
        
        # 本地未找到，尝试联网查询
        if try_online and self.enable_online_lookup:
            online_vendor = self._query_vendor_online(mac_address)
            if online_vendor:
                return online_vendor
        
        return ""
    
    def set_online_lookup(self, enabled: bool):
        """设置是否启用联网查询"""
        self.enable_online_lookup = enabled
    
    def get_online_cache_stats(self) -> dict:
        """获取联网查询缓存统计"""
        return {
            "cached_entries": len(self._online_cache),
            "cache": self._online_cache.copy()
        }

    def resolve_hostname(self, ip: str, timeout: float = 1.0) -> str:
        """
        通过DNS反向解析获取主机名

        Args:
            ip: IP地址
            timeout: 超时时间（秒）

        Returns:
            str: 主机名，失败返回空字符串
        """
        old_timeout = socket.getdefaulttimeout()
        try:
            socket.setdefaulttimeout(timeout)
            hostname, _, _ = socket.gethostbyaddr(ip)
            hostname = hostname.split(".")[0]  # 移除域名后缀
            return hostname
        except Exception:
            return ""
        finally:
            socket.setdefaulttimeout(old_timeout)

    def normalize_mac(self, mac: str) -> str:
        """
        标准化MAC地址格式

        Args:
            mac: 原始MAC地址

        Returns:
            str: 标准化后的MAC地址 (XX:XX:XX:XX:XX:XX)
        """
        if not mac:
            return ""

        # 移除所有分隔符
        mac = re.sub(r"[^0-9A-Fa-f]", "", mac)

        if len(mac) != 12:
            return ""

        # 验证是否都是十六进制字符
        try:
            int(mac, 16)
        except ValueError:
            return ""

        # 添加冒号分隔
        return ":".join(mac[i : i + 2].upper() for i in range(0, 12, 2))


